#!/usr/bin/env bash
# Writes .env for a server install (DEPLOYMENT.md): every password and secret
# from .env.example replaced by a fresh random value, plus the server
# settings. Never overwrites an existing .env.
#
#   ./scripts/new-env.sh <e-mail for certificate notices> [fhir-host] [portal-host] [auth-host]
set -euo pipefail

cd "$(dirname "$0")/.."

usage="usage: $0 <e-mail for certificate notices> [fhir-host] [portal-host] [auth-host]"
email=${1:?$usage}
fhir_host=${2:-cloud.bonolohealth.gov.ls}
portal_host=${3:-portal.bonolohealth.gov.ls}
auth_host=${4:-auth.bonolohealth.gov.ls}

if [[ -e .env ]]; then
  echo ".env already exists; not overwriting it." >&2
  exit 1
fi

umask 077
# OPENHIM_ROOT_PASSWORD keeps OpenHIM's own default: setup-openhim.sh signs
# in with it, and you change it in the console afterwards.
awk -v generated="$(date '+%Y-%m-%d %H:%M')" '
  NR == 1 { print "# Generated by scripts/new-env.sh on " generated ". Keep this file private."; next }
  /^# (Demo settings|Server installs|server settings)/ { next }
  /^OPENHIM_ROOT_PASSWORD=/ { print; next }
  /^[A-Z_]*(PASSWORD|SECRET)[A-Z_]*=/ {
    cmd = "openssl rand -hex 24"; cmd | getline value; close(cmd)
    sub(/=.*/, "=" value); print; next
  }
  { print }
' .env.example > .env

cat >> .env <<EOF

# Server (docker-compose.prod.yml)
COMPOSE_FILE=docker-compose.yml:docker-compose.prod.yml
FHIR_HOST=$fhir_host
PORTAL_HOST=$portal_host
AUTH_HOST=$auth_host
ACME_EMAIL=$email
EOF

echo "Wrote .env for https://$fhir_host, https://$portal_host and https://$auth_host."
